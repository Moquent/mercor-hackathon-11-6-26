"""Real-trace track: DAGScope's 23 RCAEval tasks (attribution / reachability / gap), asked of gpt-6-luna.

Tasks, private ground truth and span extracts were generated by DAGScope (Sarvesh, commit 5310275) from
real RCAEval fault-injection traces and are copied verbatim into cases/dagscope/rcaeval/. This module
ports their prompt builder and scoring rules (scripts/rcaeval_evaluate.py, app/evaluation/scoring.py)
to the stdlib, asks each task once in a fresh request, and grades the first answer.

    python -m rootproof.dagscope.rcaeval          # ask (skips saved attempts) then score
"""
from __future__ import annotations

import hashlib
import json
import re
from collections import deque
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ROOT = REPO / "cases" / "dagscope" / "rcaeval"
ATTEMPTS = REPO / "attempts" / "dagscope_rcaeval"
MODEL = "gpt-6-luna"
REFERENCE_MODEL_DIR = "openai_gpt-5-mini"

SYSTEM_NAMES = {"ob": "Online Boutique (Google's microservice demo: gRPC services behind a frontend)",
                "tt": "Train Ticket (a large Java microservice ticketing system)"}
# DAGScope's DEFINITIONS (app/evaluation/prompts.py) minus the commit lines, exactly as their bench uses it.
_DEFINITIONS = """Relationship definitions (the source and target are event ids; edges point parent -> dependent child):
- reachable: this export establishes a directed path of recorded dependencies from source to target.
- direct_dependency: this export establishes a single recorded edge from source to target.
- not_reachable: this export establishes that no such path exists in the execution.
- insufficient_evidence: this export establishes neither reachable nor not_reachable.
- produced_commit: the source event belongs to the delivery attempt that itself performed the committed database transaction recorded by the target event.
- not_produced_commit: the source event's delivery attempt did not perform that committed transaction.
- shared_ancestor: a third, earlier event is recorded upstream of both source and target; give its id in ancestor_event_id.
- no_shared_ancestor: no event is recorded upstream of both source and target."""
_REL_DEFS = "\n".join(line for line in _DEFINITIONS.splitlines() if "commit" not in line)


# ---------------------------------------------------------------- prompts (port of rcaeval_bench.build_prompt)

def load_tasks() -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted((ROOT / "tasks").glob("*.json"))]


def build_prompt(task: dict) -> str:
    if task["family"] == "attribution":
        return f"""You are helping investigate an incident in {SYSTEM_NAMES[task['system']]}.

{task['question']}
Incident start (UTC): {task['incident_start_utc']}
Services to choose from: {', '.join(task['candidates'])}

Trace telemetry per service and operation, before and after the incident start. A span named for a downstream call may be recorded by the calling service. Not every service necessarily reports spans.
```
{task['telemetry_table']}
```

One example trace from after the incident start (parents= gives each span's recorded parent):
```
{task['exemplar_trace']}
```

Respond with only a JSON object of this form:
{{"injected_fault_service": "...", "explanation": "...", "confidence": 0.0}}
confidence is your overall confidence between 0 and 1."""
    pairs = []
    for i, pair in enumerate(task["pairs"], 1):
        line = f"{i}. source_event_id={pair['source_event_id']} target_event_id={pair['target_event_id']} relationship: one of {', '.join(pair['allowed_relationships'])}"
        if pair["ancestor_required"]:
            line += " (include ancestor_event_id if you choose shared_ancestor)"
        pairs.append(line)
    return f"""You are helping investigate an incident in {SYSTEM_NAMES[task['system']]}.

Question: {task['question']}

Coverage of this export: PARTIAL. It came from a third-party tracing capture: some spans or dependency links of this execution may be missing from it, and some services may not report spans.
Each line is one span (event=span id), and parents= gives its recorded parent: those are the recorded dependency edges (parent -> this span).

{_REL_DEFS}

Span export:
```
{task['ai_visible_logs']}
```

Report exactly one claim per listed item:
{chr(10).join(pairs)}

Respond with only a JSON object of this form:
{{"claims": [{{"source_event_id": "...", "target_event_id": "...", "relationship": "...", "ancestor_event_id": null}}], "explanation": "...", "confidence": 0.0}}
confidence is your overall confidence between 0 and 1."""


# ---------------------------------------------------------------- parsing (port of schema.parse_answer)

_FENCE = re.compile(r"^\s*```(?:json)?\s*(.*?)\s*```\s*$", re.DOTALL)


def parse_answer(raw: str | None, family: str):
    """Strict JSON; the only tolerance is one markdown fence around the whole answer."""
    if not raw or not raw.strip():
        return None, "empty response"
    m = _FENCE.match(raw)
    text = m.group(1) if m else raw.strip()
    try:
        obj = json.loads(text)
    except json.JSONDecodeError as exc:
        return None, f"invalid JSON: {exc}"
    if not isinstance(obj, dict):
        return None, "schema violation: not an object"
    conf = obj.get("confidence")
    if not isinstance(conf, (int, float)) or isinstance(conf, bool) or not 0 <= conf <= 1:
        return None, "schema violation: confidence"
    if not isinstance(obj.get("explanation"), str):
        return None, "schema violation: explanation"
    if family == "attribution":
        if not isinstance(obj.get("injected_fault_service"), str):
            return None, "schema violation: injected_fault_service"
        return {"injected_fault_service": obj["injected_fault_service"], "explanation": obj["explanation"], "confidence": float(conf)}, None
    claims = obj.get("claims")
    if not isinstance(claims, list):
        return None, "schema violation: claims"
    out = []
    for c in claims:
        if not isinstance(c, dict) or not all(isinstance(c.get(k), str) for k in ("source_event_id", "target_event_id", "relationship")):
            return None, "schema violation: claim fields"
        anc = c.get("ancestor_event_id")
        out.append({"source_event_id": c["source_event_id"], "target_event_id": c["target_event_id"], "relationship": c["relationship"],
                    "ancestor_event_id": anc if isinstance(anc, str) else None})
    return {"claims": out, "explanation": obj["explanation"], "confidence": float(conf)}, None


# ---------------------------------------------------------------- verifier (rootproof.dagscope.verify if present)

def _private_verify_fault_origin(claimed, injected, candidates):
    base = {"claim": {"relationship": "fault_injected_in", "service": claimed}, "evidence_class": "intervention_label", "injected_service": injected}
    if not isinstance(claimed, str) or claimed not in candidates:
        return {**base, "verdict": "INVALID_CLAIM", "explanation": f"{claimed!r} is not one of the listed services."}
    if claimed == injected:
        return {**base, "verdict": "SUPPORTED", "explanation": f"The experiment injected the fault into {injected}."}
    return {**base, "verdict": "CONTRADICTED", "explanation": f"The experiment injected the fault into {injected}, not {claimed}."}


try:  # the shared stdlib port, when the other track has landed it
    from rootproof.dagscope.verify import verify_fault_origin as _shared_vfo  # type: ignore
except Exception:  # noqa: BLE001
    _shared_vfo = None


def verify_fault_origin(claimed, injected, candidates) -> dict:
    if _shared_vfo is not None:
        try:
            res = _shared_vfo(claimed, injected, candidates)
            if isinstance(res, dict) and "verdict" in res:
                v = res["verdict"]
                res["verdict"] = getattr(v, "value", v)
                return res
        except Exception:  # noqa: BLE001
            pass
    return _private_verify_fault_origin(claimed, injected, candidates)


class Graph:
    """Recorded parent -> child edges; dangling parents are placeholders, never valid claim endpoints."""

    def __init__(self, events: list[dict], deps: list[dict], closed_world: bool):
        self.known = {e["event_id"] for e in events}
        self.children: dict[str, set] = {}
        self.parents: dict[str, set] = {}
        nodes = set(self.known)
        for d in deps:
            p, c = d["parent_event_id"], d["child_event_id"]
            nodes |= {p, c}
            self.children.setdefault(p, set()).add(c)
            self.parents.setdefault(c, set()).add(p)
        # Integrity failures (dangling parents, duplicates) revoke closed-world status, as in DAGScope.
        dup = len(events) != len(self.known)
        self.closed_world = closed_world and not dup and nodes == self.known

    def _bfs(self, start, adj) -> set:
        seen, q = set(), deque([start])
        while q:
            for n in adj.get(q.popleft(), ()):
                if n not in seen:
                    seen.add(n)
                    q.append(n)
        return seen

    def reaches(self, a, b) -> bool:
        return b in self._bfs(a, self.children)

    def ancestors(self, x) -> set:
        return self._bfs(x, self.parents)


def verify_claim(raw: dict, g: Graph) -> dict:
    """Open-world-aware verdicts for the relationships the RCAEval tasks allow."""
    rel, s, t, z = raw["relationship"], raw["source_event_id"], raw["target_event_id"], raw.get("ancestor_event_id")
    for label, node in (("source", s), ("target", t)):
        if node not in g.known:
            return {"verdict": "INVALID_CLAIM", "explanation": f"{label} id {node!r} is not an event in this evidence."}
    if rel in ("reachable", "not_reachable", "insufficient_evidence", "direct_dependency"):
        if s == t:
            return {"verdict": "INVALID_CLAIM", "explanation": "source and target are the same event."}
        path = g.reaches(s, t)
        base = "SUPPORTED" if path else ("CONTRADICTED" if g.closed_world else "NOT_OBSERVED")
        if rel == "reachable":
            return {"verdict": base, "observed_reachable": path}
        if rel == "not_reachable":
            return {"verdict": {"SUPPORTED": "CONTRADICTED", "CONTRADICTED": "SUPPORTED"}.get(base, base), "observed_reachable": path}
        if rel == "insufficient_evidence":
            return {"verdict": {"NOT_OBSERVED": "SUPPORTED", "SUPPORTED": "CONTRADICTED"}.get(base, base), "observed_reachable": path}
        if t in g.children.get(s, ()):
            return {"verdict": "SUPPORTED", "observed_reachable": True}
        return {"verdict": "CONTRADICTED" if g.closed_world else "NOT_OBSERVED", "observed_reachable": path}
    if rel in ("shared_ancestor", "no_shared_ancestor"):
        if z is not None and z not in g.known:
            return {"verdict": "INVALID_CLAIM", "explanation": f"ancestor id {z!r} is not an event in this evidence."}
        if s == t or z in (s, t):
            return {"verdict": "INVALID_CLAIM", "explanation": "a shared ancestor relates three distinct events."}
        shared = g.ancestors(s) & g.ancestors(t)
        hit = (z in shared) if z else bool(shared)
        base = "SUPPORTED" if hit else ("CONTRADICTED" if g.closed_world else "NOT_OBSERVED")
        if rel == "no_shared_ancestor":
            base = {"SUPPORTED": "CONTRADICTED", "CONTRADICTED": "SUPPORTED"}.get(base, base)
        return {"verdict": base}
    return {"verdict": "INVALID_CLAIM", "explanation": f"The checker cannot evaluate {rel!r}."}


# ---------------------------------------------------------------- asking

def _attempt_path(task_id: str) -> Path:
    return ATTEMPTS / f"{task_id}.json"


def ask_one(task: dict, model: str = MODEL) -> dict:
    out = _attempt_path(task["task_id"])
    if out.exists():
        return json.loads(out.read_text())
    from rootproof.clients import ask_subject
    prompt = build_prompt(task)
    answer, raw = ask_subject(prompt, model=model)
    parsed, error = parse_answer(answer, task["family"])
    record = {"source": "model", "task_id": task["task_id"], "family": task["family"], "model": model, "response_model": raw.get("model"),
              "asked_at_utc": datetime.now(timezone.utc).isoformat(), "conversation": "fresh request; single user message; first answer kept",
              "prompt_sha256": hashlib.sha256(prompt.encode()).hexdigest(), "usage": raw.get("usage"), "raw_answer": answer,
              "parsed": parsed, "parse_error": error}
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(record, indent=1))
    return record


def ask_all(model: str = MODEL, threads: int = 6) -> list[dict]:
    tasks = load_tasks()
    with ThreadPoolExecutor(max_workers=threads) as pool:
        return list(pool.map(lambda t: ask_one(t, model), tasks))


# ---------------------------------------------------------------- scoring (port of scoring.grade / aggregate)

def _grade_reach(record: dict, truth: dict, artifact: dict) -> dict:
    base = {"task_id": truth["task_id"], "family": truth["family"], "case": truth["case"], "coverage": truth["coverage"]}
    parsed = record.get("parsed")
    if parsed is None:
        return {**base, "format_failure": True, "task_correct": False, "claims": [], "slot_results": [],
                "mismatch": f"Unparseable output: {record.get('parse_error')}"}
    try:  # the shared stdlib port of DAGScope's checker
        from rootproof.dagscope import verify as shared
        g = shared.build_dependency_dag(artifact["events"], artifact["dependencies"], artifact["coverage"])
        check = lambda c: shared.verify_claim(c, g, artifact["coverage"])  # noqa: E731
    except ImportError:
        g = Graph(artifact["events"], artifact["dependencies"], bool(artifact["coverage"].get("closed_world")))
        check = lambda c: verify_claim(c, g)  # noqa: E731
    full_pairs = {tuple(p) for p in artifact["sql_closure"]}
    claims = [{"raw": c, "result": check(c), "reachable_in_private_graph": (c["source_event_id"], c["target_event_id"]) in full_pairs}
              for c in parsed["claims"]]
    slot_results, used = [], set()
    for slot in truth["ground_truth"]["slots"]:
        match = next((i for i, c in enumerate(claims) if i not in used and c["raw"]["source_event_id"] == slot["source"]
                      and c["raw"]["target_event_id"] == slot["target"] and c["raw"]["relationship"] in slot["allowed"]), None)
        if match is None:
            slot_results.append({"slot_index": slot["slot_index"], "status": "missing", "expected": slot["relationship"], "claimed": None,
                                 "source_name": slot["source_name"], "target_name": slot["target_name"]})
            continue
        used.add(match)
        c = claims[match]
        ok = c["raw"]["relationship"] == slot["relationship"] and c["result"]["verdict"] == "SUPPORTED"
        if ok and slot["relationship"] == "shared_ancestor":
            ok = c["raw"].get("ancestor_event_id") in slot["acceptable_ancestors"]
        slot_results.append({"slot_index": slot["slot_index"], "status": "correct" if ok else "wrong", "expected": slot["relationship"],
                             "claimed": c["raw"]["relationship"], "verdict": c["result"]["verdict"],
                             "source_name": slot["source_name"], "target_name": slot["target_name"]})
    extras_rejected = [c for i, c in enumerate(claims) if i not in used and c["result"]["verdict"] != "SUPPORTED"]
    correct = all(s["status"] == "correct" for s in slot_results) and not extras_rejected
    wrong = [s for s in slot_results if s["status"] != "correct"]
    mismatch = "" if correct else "; ".join(
        f"{s['source_name']} -> {s['target_name']}: claimed {s['claimed']}, evidence supports {s['expected']}"
        + (f" (verdict {s['verdict']})" if s.get("verdict") else "") for s in wrong) or "Extra claim rejected by the checker."
    return {**base, "format_failure": False, "task_correct": correct, "claims": claims, "slot_results": slot_results,
            "confidence": parsed.get("confidence"), "mismatch": mismatch}


def _aggregate(graded: list[dict]) -> dict:
    claims = [c for g in graded for c in g["claims"]]
    verdicts = {v: sum(c["result"]["verdict"] == v for c in claims) for v in ("SUPPORTED", "CONTRADICTED", "NOT_OBSERVED", "INVALID_CLAIM")}
    fp_den = fp = fn_den = fn = cert_den = cert = 0
    for g in graded:
        complete = g["coverage"] == "complete"
        for c in g["claims"]:
            rel, in_full = c["raw"]["relationship"], c["reachable_in_private_graph"]
            if c["result"]["verdict"] == "INVALID_CLAIM":
                continue
            if rel in ("reachable", "direct_dependency"):
                fp_den += 1
                fp += not in_full
            if rel == "not_reachable" and complete:
                fn_den += 1
                fn += in_full
            if not complete and rel in ("reachable", "not_reachable", "direct_dependency"):
                cert_den += 1
                cert += c["result"]["verdict"] == "NOT_OBSERVED"
    return {"tasks_evaluated": len(graded), "tasks_correct": sum(g["task_correct"] for g in graded),
            "format_failures": sum(g["format_failure"] for g in graded), "claims_total": len(claims),
            "claims_accepted": verdicts["SUPPORTED"], "claims_rejected": verdicts["CONTRADICTED"] + verdicts["INVALID_CLAIM"],
            "claims_inconclusive": verdicts["NOT_OBSERVED"], "verdict_counts": verdicts,
            "false_positive_reachability": {"count": fp, "denominator": fp_den},
            "false_negative_reachability_complete": {"count": fn, "denominator": fn_den},
            "incorrect_certainty_incomplete": {"count": cert, "denominator": cert_den}}


def score(model: str = MODEL, attempts_dir: Path = ATTEMPTS) -> dict:
    graded, attributions, misses = [], [], []
    for task in load_tasks():
        path = attempts_dir / f"{task['task_id']}.json"
        if not path.exists():
            continue
        record = json.loads(path.read_text())
        truth = json.loads((ROOT / "ground_truth" / f"{task['task_id']}.json").read_text())
        if task["family"] == "attribution":
            gt, parsed = truth["ground_truth"], record.get("parsed")
            result = verify_fault_origin(parsed["injected_fault_service"], gt["injected_service"], task["candidates"]) if parsed else None
            row = {"task_id": task["task_id"], "case": truth["case"], "family": "attribution", "format_failure": parsed is None,
                   "claimed": parsed["injected_fault_service"] if parsed else None, "confidence": parsed["confidence"] if parsed else None,
                   "injected_service": gt["injected_service"], "fault": gt["fault"], "verdict": result["verdict"] if result else None,
                   "service_present_in_traces": gt["service_present_in_traces"], "naive_baseline": gt["naive_error_blame_baseline"],
                   "naive_correct": gt["naive_error_blame_baseline"] == gt["injected_service"],
                   "task_correct": bool(result and result["verdict"] == "SUPPORTED")}
            attributions.append(row)
            if not row["task_correct"]:
                misses.append({"task_id": task["task_id"], "detail": f"claimed {row['claimed']}, injected {row['injected_service']} (fault {row['fault']}, stated confidence {row['confidence']})"})
        else:
            artifact = json.loads((ROOT / "extracts" / f"{task['task_id']}.json").read_text())
            row = _grade_reach(record, truth, artifact)
            graded.append(row)
            if not row["task_correct"]:
                misses.append({"task_id": task["task_id"], "detail": row["mismatch"]})
    wrong_naive = [a for a in attributions if not a["naive_correct"]]
    absent = [a for a in attributions if not a["service_present_in_traces"]]
    by_family = {f: {"tasks": sum(g["family"] == f for g in graded), "correct": sum(g["task_correct"] for g in graded if g["family"] == f)}
                 for f in ("reachability", "gap")}
    return {"model_name": model,
            "attribution": {"tasks": len(attributions), "correct": sum(a["task_correct"] for a in attributions),
                            "format_failures": sum(a["format_failure"] for a in attributions),
                            "naive_correct": sum(a["naive_correct"] for a in attributions), "naive_wrong": len(wrong_naive),
                            "correct_when_naive_wrong": sum(a["task_correct"] for a in wrong_naive),
                            "service_absent": len(absent), "correct_service_absent": sum(a["task_correct"] for a in absent)},
            "reachability": {**_aggregate(graded), "by_family": by_family},
            "misses": misses, "per_task": graded + attributions}


def report(model: str = MODEL) -> dict:
    """gpt-6-luna scored here; gpt-5-mini re-scored from DAGScope's saved attempts with the same code, plus
    their own saved metrics for cross-checking the port."""
    ours = score(model)
    ref_dir = ROOT / "attempts" / REFERENCE_MODEL_DIR
    ref = score("openai/gpt-5-mini", ref_dir)
    saved = json.loads((ROOT / "results" / REFERENCE_MODEL_DIR / "metrics.json").read_text())
    a = ours["attribution"]
    table = {
        "attribution_correct": {model: f"{a['correct']}/{a['tasks']}", "gpt-5-mini": f"{ref['attribution']['correct']}/{ref['attribution']['tasks']}",
                                "naive_error_blame": f"{a['naive_correct']}/{a['tasks']}"},
        "attribution_correct_when_naive_wrong": {model: f"{a['correct_when_naive_wrong']}/{a['naive_wrong']}",
                                                 "gpt-5-mini": f"{ref['attribution']['correct_when_naive_wrong']}/{ref['attribution']['naive_wrong']}"},
        "reach_gap_tasks_correct": {model: f"{ours['reachability']['tasks_correct']}/{ours['reachability']['tasks_evaluated']}",
                                    "gpt-5-mini": f"{ref['reachability']['tasks_correct']}/{ref['reachability']['tasks_evaluated']}"},
        "incorrect_certainty_incomplete": {
            model: f"{ours['reachability']['incorrect_certainty_incomplete']['count']}/{ours['reachability']['incorrect_certainty_incomplete']['denominator']}",
            "gpt-5-mini": f"{ref['reachability']['incorrect_certainty_incomplete']['count']}/{ref['reachability']['incorrect_certainty_incomplete']['denominator']}"},
    }
    port_check = {"attribution_correct_matches_saved": ref["attribution"]["correct"] == saved["attribution"]["correct"],
                  "reach_tasks_correct_matches_saved": ref["reachability"]["tasks_correct"] == saved["reachability"]["tasks_correct"],
                  "verdict_counts_match_saved": ref["reachability"]["verdict_counts"] == saved["reachability"]["verdict_counts"]}
    return {"source": "DAGScope RCAEval external benchmark (Sarvesh, commit 5310275); real RCAEval fault-injection traces",
            "scored_at_utc": datetime.now(timezone.utc).isoformat(), "comparison": table, "port_check_vs_saved_gpt-5-mini": port_check,
            model: {k: v for k, v in ours.items() if k != "per_task"}, "gpt-5-mini": {k: v for k, v in ref.items() if k != "per_task"},
            "per_task": ours["per_task"]}


def main() -> int:
    ask_all()
    out = report()
    (ROOT / f"results_{MODEL}.json").write_text(json.dumps(out, indent=1, default=str))
    print(json.dumps({"comparison": out["comparison"], "port_check": out["port_check_vs_saved_gpt-5-mini"]}, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
